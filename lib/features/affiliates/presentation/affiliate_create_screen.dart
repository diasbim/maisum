/// The confirmation, with the code the server actually minted.
///
/// Sharing is only offered once that code exists and is usable. A provisional
/// code — one this device invented while offline — is never shareable, because
/// the person who receives it would type it at the counter and be refused.
class _CreatedPanel extends ConsumerWidget {
  const _CreatedPanel({required this.affiliate});

  final MerchantAffiliate affiliate;

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    final code = affiliate.code;
    final businessName =
        ref.watch(authControllerProvider).valueOrNull?.merchantName ?? '';
    final draft = buildAffiliateShareDraft(
      affiliate: affiliate,
      businessName: businessName,
    );

    return Column(
      crossAxisAlignment: CrossAxisAlignment.stretch,
      children: [
        MaisUmSurface(
          key: const Key('affiliate-created-panel'),
          variant: MaisUmSurfaceVariant.success,
          radius: AppRadius.lg,
          padding: const EdgeInsets.all(AppSpacing.lg),
          animationDuration: Duration.zero,
          child: Column(
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              Row(
                children: [
                  const Icon(Icons.check_circle_rounded,
                      color: AppColors.success),
                  const SizedBox(width: AppSpacing.sm),
                  Expanded(
                    child: Text(
                      '${affiliate.name} é agora afiliado',
                      style: const TextStyle(
                        fontWeight: FontWeight.w800,
                        color: AppColors.onSurface,
                      ),
                    ),
                  ),
                ],
              ),
              const SizedBox(height: AppSpacing.lg),
              const Text(
                'Código confirmado',
                style: TextStyle(color: AppColors.onSurfaceVariant),
              ),
              const SizedBox(height: AppSpacing.xs),
              SelectableText(
                code?.code.toUpperCase() ?? '—',
                key: const Key('affiliate-created-code'),
                style: const TextStyle(
                  fontSize: 24,
                  fontWeight: FontWeight.w900,
                  letterSpacing: 1.5,
                  color: AppColors.onSurface,
                ),
              ),
            ],
          ),
        ),
        const SizedBox(height: AppSpacing.lg),
        if (draft == null)
          const AffiliateOfflineNotice(
            message: 'Este código ainda não está confirmado pelo sistema, '
                'por isso não pode ser partilhado.',
          ),
        if (draft != null)
          MaisUmButton(
            key: const Key('affiliate-share-button'),
            label: 'Partilhar código',
            leadingIcon: Icons.share_rounded,
            onPressed: () => _share(context, draft),
            animationDuration: Duration.zero,
          ),
        const SizedBox(height: AppSpacing.md),
        MaisUmButton(
          label: 'Ver afiliado',
          variant: MaisUmButtonVariant.outlined,
          foregroundColor: AppColors.primary,
          onPressed: () => context.pushReplacement(
            '/affiliates/${affiliate.id}',
          ),
          animationDuration: Duration.zero,
        ),
      ],
    );
  }

  Future<void> _share(BuildContext context, AffiliateShareDraft draft) async {
    final launched = await launchUrl(
      draft.uri,
      mode: LaunchMode.externalApplication,
    );
    if (!launched && context.mounted) {
      AppFeedback.showMessage(
        context,
        message: 'Não foi possível abrir o WhatsApp.',
        isError: true,
      );
    }
  }
}
