          ),
        ],
      ),
    );
  }
}

class _SectionLabel extends StatelessWidget {
  const _SectionLabel(this.text);

  final String text;

  @override
  Widget build(BuildContext context) {
    return Semantics(
      header: true,
      child: Text(
        text,
        style: const TextStyle(
          fontWeight: FontWeight.w800,
          color: AppColors.onSurface,
        ),
      ),
    );
  }
}

class _BenefitTypeSelector extends StatelessWidget {
  const _BenefitTypeSelector({required this.selected, required this.onChanged});

  final ReferralBenefitType selected;
  final ValueChanged<ReferralBenefitType> onChanged;

  @override
  Widget build(BuildContext context) {
    return Wrap(
      spacing: AppSpacing.sm,
      runSpacing: AppSpacing.sm,
      children: [
        for (final type in ReferralBenefitType.values)
          ChoiceChip(
            label: Text(_label(type)),
            selected: selected == type,
            onSelected: (_) => onChanged(type),
            padding: const EdgeInsets.symmetric(
              horizontal: AppSpacing.md,
              vertical: AppSpacing.sm,
            ),
          ),
      ],
    );
  }

  static String _label(ReferralBenefitType type) => switch (type) {
        ReferralBenefitType.percentage => 'Percentagem',
        ReferralBenefitType.fixedAmount => 'Valor em MT',
        ReferralBenefitType.points => 'Pontos',
      };
}

class _ExpirySelector extends StatelessWidget {
  const _ExpirySelector({required this.days, required this.onChanged});

  final int days;
  final ValueChanged<int> onChanged;

  static const _options = <int>[30, 60, 90, 180];

  @override
  Widget build(BuildContext context) {
    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        const Text(
          'Validade do código',
          style: TextStyle(color: AppColors.onSurfaceVariant),
        ),
        const SizedBox(height: AppSpacing.sm),
        Wrap(
          spacing: AppSpacing.sm,
          runSpacing: AppSpacing.sm,
          children: [
            for (final option in _options)
              ChoiceChip(
                label: Text('$option dias'),
                selected: days == option,
                onSelected: (_) => onChanged(option),
                padding: const EdgeInsets.symmetric(
                  horizontal: AppSpacing.md,
                  vertical: AppSpacing.sm,
                ),
              ),
          ],
        ),
      ],
    );
  }
}

